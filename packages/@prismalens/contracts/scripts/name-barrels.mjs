// Rewrites dist's runtime barrels from `export *` into named re-exports, each name pointing at
// the module that defines it. A bundler can only skip a barrel's unused modules when it names
// them, so a page then loads the contracts modules it uses and no others (#1130).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const DIST = resolve(dirname(fileURLToPath(import.meta.url)), "../dist");
const STAR = /^export \* from "(\.[^"]+)";$/gm;
const NAMED = /^export \{([^}]*)\} from "(\.[^"]+)";$/gm;

/** name -> { file, value } for every runtime export a barrel gives, resolved to its origin. */
async function origins(file) {
	const src = readFileSync(file, "utf8");
	const out = new Map();
	const ambiguous = new Set();
	const add = (name, file, value) => {
		const had = out.get(name);
		// Two star exports of different bindings under one name export neither, as ESM does.
		if (had && had.value !== value) ambiguous.add(name);
		else if (!had) out.set(name, { file, value });
	};
	const ns = await import(pathToFileURL(file).href);
	const own = new Set(Object.keys(ns));
	const stars = [...src.matchAll(STAR)].map((m) =>
		resolve(dirname(file), m[1]),
	);
	const named = [...src.matchAll(NAMED)].map((m) => ({
		file: resolve(dirname(file), m[2]),
		names: m[1]
			.split(",")
			.map((s) => s.trim())
			.filter(Boolean)
			.map((s) => s.split(/\s+as\s+/).at(-1)),
	}));
	for (const n of named)
		for (const name of n.names) {
			own.delete(name);
			add(name, n.file, ns[name]);
		}
	for (const star of stars) {
		const inner = await origins(star);
		const starNs = await import(pathToFileURL(star).href);
		for (const name of Object.keys(starNs)) {
			if (name === "default") continue;
			own.delete(name);
			add(name, inner.get(name)?.file ?? star, starNs[name]);
		}
	}
	// Whatever is left is the barrel's own code (the combined `contract`).
	for (const name of own) add(name, file, ns[name]);
	for (const name of ambiguous) out.delete(name);
	return out;
}

for (const rel of ["index.js", "schemas/index.js"]) {
	const file = resolve(DIST, rel);
	const src = readFileSync(file, "utf8");
	if (!STAR.test(src)) continue;
	STAR.lastIndex = 0;
	const map = await origins(file);
	if ([...map.values()].some((o) => o.file === file))
		throw new Error(
			`${rel} defines its own exports; only a pure barrel can be named.`,
		);
	const byFile = new Map();
	for (const [name, o] of map)
		byFile.set(o.file, [...(byFile.get(o.file) ?? []), name]);
	const lines = [...byFile]
		.sort(([a], [b]) => a.localeCompare(b))
		.map(([f, names]) => {
			let spec = relative(dirname(file), f).split("\\").join("/");
			if (!spec.startsWith(".")) spec = `./${spec}`;
			return `export { ${names.sort().join(", ")} } from "${spec}";`;
		});
	writeFileSync(
		file,
		`// Generated by scripts/name-barrels.mjs from the tsc output.\n${lines.join("\n")}\n`,
	);
}
